"""Render the AWS foundation's Terraform outputs into gitignored config (plan v0.10, v0.12).

    uv run python scripts/render-config.py          (make render-config)

Reads ``terraform output -json`` of every applied stack (``scripts/tf.sh output``) and writes:

- ``.generated/foundation.json``: all outputs, per stack
- ``.generated/foundation.env``: shell exports the later tags consume, e.g.
  ``AGENTCORE_SUBNETS`` / ``AGENTCORE_SECURITY_GROUPS`` / ``AGENTCORE_EXECUTION_ROLE_ARN`` /
  ``AGENTCORE_TEMPORAL_ADDRESS`` for ``scripts/render-agentcore-json.py`` (v0.12, VPC mode),
  ``TEMPORAL_SERVER_WCI_ROLE_ARN`` for ``scripts/invoke-role.sh`` and the Helm values
  (v0.11), ``RDS_ADDRESS``, ``ECR_*`` and ``EKS_CLUSTER_NAME``.

Both files carry account and resource IDs, so they live under ``.generated/`` (gitignored).
stdout is a redacted summary only.
"""

from __future__ import annotations

import json
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STACKS = ["00-guardrails", "10-network", "20-platform", "30-agentcore-iam"]
FRONTEND_PORT = 7233


def outputs(stack: str) -> dict[str, object]:
    state = ROOT / "infra" / "terraform" / stack / "terraform.tfstate"
    if not state.exists() or state.stat().st_size == 0:
        return {}
    raw = subprocess.run(
        [str(ROOT / "scripts" / "tf.sh"), "output", stack, "-json"],
        check=True,
        capture_output=True,
        text=True,
        cwd=ROOT,
    ).stdout
    return {k: v["value"] for k, v in json.loads(raw).items()}


def main() -> int:
    tf = {s: outputs(s) for s in STACKS}
    net, plat, iam = tf["10-network"], tf["20-platform"], tf["30-agentcore-iam"]
    if not net or not plat:
        print("render-config: apply 10-network and 20-platform first", file=sys.stderr)
        return 1

    sgs = net["security_group_ids"]
    assert isinstance(sgs, dict)
    zone = str(net["private_zone_name"])
    ecr = plat["ecr_repository_urls"]
    assert isinstance(ecr, dict)
    env: dict[str, str] = {
        "AWS_REGION": "us-east-1",
        "VPC_ID": str(net["vpc_id"]),
        "PRIVATE_ZONE_ID": str(net["private_zone_id"]),
        "PRIVATE_ZONE_NAME": zone,
        # AgentCore VPC mode (v0.12): every private subnet is on a supported AZ ID.
        "AGENTCORE_SUBNETS": ",".join(net["private_subnet_ids"]),  # type: ignore[arg-type]
        "AGENTCORE_SECURITY_GROUPS": str(sgs["agentcore_worker"]),
        "AGENTCORE_TEMPORAL_ADDRESS": f"temporal-frontend.{zone}:{FRONTEND_PORT}",
        "AGENTCORE_TEMPORAL_TLS_SERVER_NAME": f"temporal-frontend.{zone}",
        "NLB_SECURITY_GROUP": str(sgs["nlb_temporal_frontend"]),
        "EKS_CLUSTER_NAME": str(plat["cluster_name"]),
        "EKS_NODE_GROUP": str(plat["node_group_name"]),
        "RDS_IDENTIFIER": str(plat["rds_identifier"]),
        "RDS_ADDRESS": str(plat["rds_address"]),
        "RDS_PORT": str(plat["rds_port"]),
        "RDS_MASTER_SECRET_ARN": str(plat["rds_master_secret_arn"]),
        "TEMPORAL_SERVER_WCI_ROLE_ARN": str(plat["temporal_server_wci_role_arn"]),
        "AGENT_SERVICES_WORKER_ROLE_ARN": str(plat["agent_services_worker_role_arn"]),
        "ECR_FINANCE_AGENT": str(ecr["agentcore-demo/finance-agent"]),
        "ECR_PAYMENTS_MOCK": str(ecr["agentcore-demo/payments-mock"]),
    }
    if iam:
        env["AGENTCORE_EXECUTION_ROLE_ARN"] = str(iam["execution_role_arn"])

    out = ROOT / ".generated"
    out.mkdir(exist_ok=True)
    (out / "foundation.json").write_text(json.dumps(tf, indent=2, sort_keys=True) + "\n")
    lines = ["# Generated by make render-config from Terraform outputs. Gitignored: holds IDs."]
    lines += [f"export {k}={shlex.quote(v)}" for k, v in env.items()]
    (out / "foundation.env").write_text("\n".join(lines) + "\n")

    print("render-config: wrote .generated/foundation.json and .generated/foundation.env")
    print("  stacks: " + ", ".join(s for s, o in tf.items() if o))
    print("  keys:   " + " ".join(env))
    return 0


if __name__ == "__main__":
    sys.exit(main())
