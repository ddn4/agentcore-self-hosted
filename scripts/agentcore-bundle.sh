#!/usr/bin/env bash
# Build the AgentCore CodeZip code location for Support (plan 2.2 layout rules, v0.7).
#   scripts/agentcore-bundle.sh            (make agentcore-bundle) -> build/agentcore/
# AgentCore CodeZip cannot resolve uv workspace path dependencies, so the bundle is flat:
#   agentcore_worker.py        entrypoint (serves support_agent.agentcore_app)
#   support_agent/             the service (incl. data/)
#   finance_a2a_api/           vendored copy of the shared contract (the only shared code)
#   pyproject.toml             generated; [project].dependencies = the pins from
#                              uv export --package support-agent --frozen --no-dev --no-hashes --no-emit-workspace
#   BUILD_ID                   scripts/build-id.sh (TEMPORAL_BUILD_ID overrides for throwaway runs)
#   agentcore/agentcore.json   rendered from services/support-agent/agentcore/agentcore.json.tmpl
# v0.8 (ledger 22): AgentCore CLI 1.0.1 packages CodeZip with
#   uv pip install -r pyproject.toml --target <staging> --python-version 3.12 \
#     --python-platform aarch64-manylinux2014 --only-binary :all:
# (@aws/agentcore-cdk 1.0.0, packaging/python.js), so pyproject.toml is the one file read;
# requirements.txt was dropped from the bundle (the export is only an intermediate here).
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

OUT=build/agentcore
BUILD_ID="${TEMPORAL_BUILD_ID:-$(scripts/build-id.sh)}"
rm -rf "$OUT"; mkdir -p "$OUT/agentcore"

cp services/support-agent/agentcore/agentcore_worker.py "$OUT/"
cp -R services/support-agent/src/support_agent "$OUT/support_agent"
cp -R packages/finance-a2a-api/src/finance_a2a_api "$OUT/finance_a2a_api"
find "$OUT" -name __pycache__ -type d -prune -exec rm -rf {} +
printf '%s\n' "$BUILD_ID" >"$OUT/BUILD_ID"

REQS="$(mktemp)"; trap 'rm -f "$REQS"' EXIT
uv export --package support-agent --frozen --no-dev --no-hashes --no-emit-workspace \
  --output-file "$REQS" >/dev/null
if grep -vE "^[[:space:]]*#" "$REQS" | grep -qE "finance-a2a-api|^-e |file://"; then
  echo "agentcore-bundle: workspace path dependency leaked into the export" >&2; exit 1
fi
uv run --frozen python - "$OUT" "$REQS" <<'PY'
"""Generate a minimal pyproject.toml whose dependencies are the exported pins."""
import pathlib
import sys

out = pathlib.Path(sys.argv[1])
reqs = []
for line in pathlib.Path(sys.argv[2]).read_text().splitlines():
    line = line.strip()
    if line and not line.startswith(("#", "-")):
        reqs.append(line)
deps = "\n".join(f'    "{r}",' for r in reqs)
(out / "pyproject.toml").write_text(
    "# Generated by scripts/agentcore-bundle.sh from uv export. Do not edit.\n"
    "[project]\n"
    'name = "support-supervisor-agentcore"\n'
    'version = "0.0.0"\n'
    'description = "Support Supervisor Temporal Worker for AgentCore Runtime (CodeZip)"\n'
    'requires-python = ">=3.12,<3.13"\n'
    f"dependencies = [\n{deps}\n]\n\n"
    "# No [build-system]: the code location is run in place, only dependencies are installed.\n"
    "[tool.uv]\n"
    "package = false\n"
)
print(f"agentcore-bundle: {len(reqs)} pinned dependencies")
PY
uv run --frozen python scripts/render-agentcore-json.py --build-id "$BUILD_ID" --out "$OUT/agentcore"

files=$(find "$OUT" -type f | wc -l | tr -d ' ')
echo "agentcore-bundle: $OUT ready (Build ID $BUILD_ID, $files files, $(du -sh "$OUT" | cut -f1) of code)"
