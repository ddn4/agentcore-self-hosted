#!/usr/bin/env bash
# The EKS cluster from the laptop, without touching ~/.kube/config or its current context.
#   scripts/eks.sh kubeconfig      (make eks-kubeconfig)  write .temporal/kubeconfig-eks, context
#                                  agentcore-demo-eks (aws eks update-kubeconfig --kubeconfig ...)
#   scripts/eks.sh env             (make eks-env)         print the KUBECONFIG export for kubectl by hand
#   scripts/eks.sh status          (make eks-status)      nodes, add-ons, LBC, cert-manager, Temporal, Finance (redacted)
# v0.11 (plan v0.11, runbook Phase 2, 3, 4.1, 7b):
#   scripts/eks.sh namespace       kubectl create namespace temporal (runbook 1.3: before secrets/certs)
#   scripts/eks.sh rds-ca          Secret temporal/rds-ca from the official us-east-1 RDS bundle
#   scripts/eks.sh certs           cert-manager issuers + Temporal certificates (overlays/eks)
#   scripts/eks.sh values          render .generated/values.eks.ids.yaml (RDS address, IRSA role ARN)
#   scripts/eks.sh temporal        (make eks-temporal) namespace, rds-ca, certs, values, then
#                                  helm template | kubectl apply --dry-run=server, then
#                                  helm upgrade --install --timeout 900s, frontend NetworkPolicies
#                                  (incl. the generated NLB one); needs scripts/create-db-user.sh first
#   scripts/eks.sh netpol-nlb      NetworkPolicy temporal-frontend-from-nlb: the NLB ENIs' /32s
#   scripts/eks.sh pf              (make pf TEMPORAL_PROFILE=eks-pf) frontend -> 127.0.0.1:7233, UI -> :8233
#   scripts/eks.sh pf-stop         (make pf-stop TEMPORAL_PROFILE=eks-pf)
#   scripts/eks.sh finance-image   (make finance-image) build linux/arm64 Finance + payments-mock, push to ECR
#   scripts/eks.sh finance-deploy  (make finance-deploy) overlays/eks/temporal-workers + generated layer
#                                  (ECR images, IRSA annotation, FINANCE_BEDROCK_MODEL_ID); 2 pods
#   scripts/eks.sh scale-finance N kubectl scale deploy/agent-services-worker --replicas=N (failure demo)
# The API endpoint accepts only the laptop's public /32 (20-platform public_access_cidrs): if
# the laptop's IP changed, update infra/terraform/20-platform/terraform.auto.tfvars and re-plan.
# Docker: always DOCKER_CONTEXT (default colima-agentcore); the global context is never changed.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
export AWS_REGION=us-east-1 AWS_PAGER=""
export DOCKER_CONTEXT="${DOCKER_CONTEXT:-colima-agentcore}"
CLUSTER="${CLUSTER:-temporal}"
KCFG="$PWD/.temporal/kubeconfig-eks"
CONTEXT=agentcore-demo-eks
CHART_REPO=https://go.temporal.io/helm-charts
CHART_VERSION=1.7.0
RDS_CA_URL=https://truststore.pki.rds.amazonaws.com/us-east-1/us-east-1-bundle.pem
FOUNDATION=.generated/foundation.env
IDS=.generated/values.eks.ids.yaml
IMAGES=.generated/finance-images.env
PIDS=.temporal/eks-pf
log() { printf '[eks] %s\n' "$*"; }

kube() {
  [[ -f "$KCFG" ]] || "$0" kubeconfig >/dev/null
  export KUBECONFIG="$KCFG"
}
k() { kubectl --context "$CONTEXT" "$@"; }
h() { helm --kube-context "$CONTEXT" "$@"; }
foundation() {
  [[ -f "$FOUNDATION" ]] || { echo "eks: run 'make render-config' first ($FOUNDATION)" >&2; exit 1; }
  # shellcheck disable=SC1090
  source "$FOUNDATION"
}

values_args() {
  VALS=(-f deploy/temporal/values.postgresql.yaml -f deploy/temporal/values.base.yaml
        -f deploy/temporal/values.tls.yaml -f deploy/temporal/values.eks.yaml -f "$IDS")
}

cmd_namespace() {
  kube
  k create namespace temporal --dry-run=client -o yaml | k apply -f - >/dev/null
  log "namespace temporal"
}

cmd_rds_ca() {
  kube; cmd_namespace
  local tmp; tmp="$(mktemp -d)"
  curl -fsS "$RDS_CA_URL" -o "$tmp/rds-ca.pem"
  local n; n="$(grep -c 'BEGIN CERTIFICATE' "$tmp/rds-ca.pem")"
  [[ "$n" -ge 1 ]] || { echo "eks: $RDS_CA_URL returned no certificates" >&2; rm -rf "$tmp"; exit 1; }
  k create secret generic rds-ca -n temporal --from-file=rds-ca.pem="$tmp/rds-ca.pem" \
    --dry-run=client -o yaml | k apply -f - >/dev/null
  rm -rf "$tmp"
  log "Secret temporal/rds-ca: $n CA certificates from $RDS_CA_URL"
}

cmd_certs() {
  kube; cmd_namespace
  k apply -k deploy/k8s/overlays/eks/cert-issuers >/dev/null
  k wait --for=condition=Ready certificate/temporal-root-ca -n cert-manager --timeout=120s >/dev/null
  k wait --for=condition=Ready clusterissuer/temporal-ca --timeout=120s >/dev/null
  k apply -k deploy/k8s/overlays/eks/temporal-certs >/dev/null
  k wait --for=condition=Ready certificate --all -n temporal --timeout=180s >/dev/null
  log "cert-manager: temporal-root-ca -> temporal-ca; $(k get certificate -n temporal --no-headers | wc -l | tr -d ' ') certificates Ready in temporal"
}

cmd_values() {
  foundation
  mkdir -p .generated
  umask 077
  cat >"$IDS" <<EOF
# Generated by scripts/eks.sh values from $FOUNDATION (gitignored: account / resource IDs).
server:
  config:
    persistence:
      datastores:
        default:
          sql:
            connectAddr: "$RDS_ADDRESS:$RDS_PORT"
        visibility:
          sql:
            connectAddr: "$RDS_ADDRESS:$RDS_PORT"
  worker:
    serviceAccount:
      extraAnnotations:
        eks.amazonaws.com/role-arn: "$TEMPORAL_SERVER_WCI_ROLE_ARN"
EOF
  log "wrote $IDS"
}

cmd_temporal() {
  kube
  k get secret temporal-db-secret -n temporal >/dev/null 2>&1 \
    || { echo "eks: Secret temporal/temporal-db-secret missing: run scripts/create-db-user.sh first" >&2; exit 1; }
  cmd_rds_ca
  cmd_certs
  cmd_values
  values_args
  log "values: ${VALS[*]}"
  log "dry run: helm template | kubectl apply --dry-run=server (runbook 2.11 step 2)"
  h template temporal temporal --repo "$CHART_REPO" --version "$CHART_VERSION" \
    "${VALS[@]}" --namespace temporal | k apply --dry-run=server -n temporal -f - >/dev/null
  log "helm upgrade --install temporal (chart $CHART_VERSION, --timeout 900s)"
  h upgrade --install temporal temporal --repo "$CHART_REPO" --version "$CHART_VERSION" \
    "${VALS[@]}" --namespace temporal --wait --timeout 900s
  for d in frontend history matching worker web admintools; do
    k rollout status "deploy/temporal-$d" -n temporal --timeout=300s >/dev/null
  done
  k apply -k deploy/k8s/overlays/eks/temporal-network >/dev/null
  cmd_netpol_nlb
  log "Temporal is up on EKS"
}

nlb_ips() {
  aws ec2 describe-network-interfaces \
    --filters "Name=description,Values=ELB net/temporal-frontend/*" \
    --query 'NetworkInterfaces[].PrivateIpAddress' --output text
}

cmd_netpol_nlb() {
  kube
  local ips=""
  for _ in $(seq 1 60); do
    ips="$(nlb_ips)"; [[ -n "$ips" && "$ips" != None ]] && break; sleep 5
  done
  [[ -n "$ips" && "$ips" != None ]] || { echo "eks: no ENIs for NLB temporal-frontend yet" >&2; exit 1; }
  {
    cat <<'EOF'
# Generated by scripts/eks.sh netpol-nlb (plan v0.11; runbook 7b.6): the internal NLB's ENIs
# (ip targets, preserve_client_ip off -> pods see these source IPs) may reach 7233. Health
# checks come from the same IPs. Nothing else in the VPC CIDR is admitted.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata: { name: temporal-frontend-from-nlb, namespace: temporal }
spec:
  podSelector:
    matchLabels: { app.kubernetes.io/name: temporal, app.kubernetes.io/component: frontend }
  policyTypes: [Ingress]
  ingress:
    - ports: [{ protocol: TCP, port: 7233 }]
      from:
EOF
    for ip in $ips; do printf '        - ipBlock: { cidr: %s/32 }\n' "$ip"; done
  } | k apply -f - >/dev/null
  log "NetworkPolicy temporal-frontend-from-nlb: $(wc -w <<<"$ips" | tr -d ' ') NLB ENI addresses"
}

pf_one() {  # pf_one NAME SVC LOCAL REMOTE  (supervised: a reset connection ends kubectl port-forward)
  local pidf="$PIDS-$1.pid"
  if [[ -f "$pidf" ]] && kill -0 "$(cat "$pidf")" 2>/dev/null; then log "pf $1 already running"; return; fi
  if nc -z 127.0.0.1 "$3" 2>/dev/null; then echo "eks: 127.0.0.1:$3 is in use (kind pf? make pf-stop)" >&2; exit 1; fi
  nohup bash -c 'while true; do
      kubectl --context agentcore-demo-eks port-forward -n temporal "svc/$1" "$2:$3" --address 127.0.0.1
      sleep 0.3
    done' pf "$2" "$3" "$4" >".temporal/eks-pf-$1.log" 2>&1 &
  echo $! >"$pidf"
  for _ in $(seq 1 75); do nc -z 127.0.0.1 "$3" 2>/dev/null && { log "pf $1: 127.0.0.1:$3 -> svc/$2:$4"; return; }; sleep 0.2; done
  echo "eks: pf $1 did not come up; see .temporal/eks-pf-$1.log" >&2; exit 1
}

cmd_pf() {
  kube
  pf_one frontend temporal-frontend 7233 7233
  pf_one web temporal-web 8233 8080
}

cmd_pf_stop() {
  local pid kids
  for f in "$PIDS"-*.pid; do
    [[ -f "$f" ]] || continue
    pid="$(cat "$f")"
    kids="$(pgrep -P "$pid" 2>/dev/null || true)"     # the kubectl child, before it is re-parented
    kill "$pid" 2>/dev/null || true                     # the supervisor loop first (no restart) ...
    [[ -z "$kids" ]] || kill $kids 2>/dev/null || true  # ... then its kubectl
    rm -f "$f"
  done
  log "port-forwards stopped"
}

cmd_finance_image() {
  foundation
  local registry="${ECR_FINANCE_AGENT%%/*}"
  log "building linux/arm64 images (docker context $DOCKER_CONTEXT; m7g nodes are arm64)"
  docker build -q --platform linux/arm64 -f services/finance-agent/Dockerfile --target finance \
    -t agentcore-demo/finance-agent:eks . >/dev/null
  docker build -q --platform linux/arm64 -f services/payments-mock/Dockerfile \
    -t agentcore-demo/payments-mock:eks . >/dev/null
  # Content-addressed tags: the local image ID (same build inputs -> same tag).
  local fin pay
  fin="img-$(docker image inspect agentcore-demo/finance-agent:eks --format '{{.Id}}' | cut -d: -f2 | cut -c1-12)"
  pay="img-$(docker image inspect agentcore-demo/payments-mock:eks --format '{{.Id}}' | cut -d: -f2 | cut -c1-12)"
  aws ecr get-login-password | docker login --username AWS --password-stdin "$registry" >/dev/null
  docker tag agentcore-demo/finance-agent:eks "$ECR_FINANCE_AGENT:$fin"
  docker tag agentcore-demo/payments-mock:eks "$ECR_PAYMENTS_MOCK:$pay"
  docker push -q "$ECR_FINANCE_AGENT:$fin" >/dev/null
  docker push -q "$ECR_PAYMENTS_MOCK:$pay" >/dev/null
  docker logout "$registry" >/dev/null 2>&1 || true
  mkdir -p .generated
  printf 'FINANCE_IMAGE_TAG=%s\nPAYMENTS_IMAGE_TAG=%s\n' "$fin" "$pay" >"$IMAGES"
  log "pushed agentcore-demo/finance-agent:$fin and agentcore-demo/payments-mock:$pay (linux/arm64)"
  aws ecr describe-images --repository-name agentcore-demo/finance-agent --image-ids imageTag="$fin" \
    --query 'imageDetails[0].{tag:imageTags[0],bytes:imageSizeInBytes,pushed:imagePushedAt}' --output json | scripts/redact.sh
}

cmd_finance_deploy() {
  kube; foundation
  [[ -f "$IMAGES" ]] || { echo "eks: run 'make finance-image' first ($IMAGES)" >&2; exit 1; }
  # shellcheck disable=SC1090
  source "$IMAGES"
  local model="${FINANCE_BEDROCK_MODEL_ID:-global.anthropic.claude-opus-5-5}"
  local dir=.generated/eks-temporal-workers
  mkdir -p "$dir"
  cat >"$dir/kustomization.yaml" <<EOF
# Generated by scripts/eks.sh finance-deploy (gitignored: ECR host and role ARN carry the account ID).
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../deploy/k8s/overlays/eks/temporal-workers
images:
  - { name: agentcore-demo/finance-agent, newName: $ECR_FINANCE_AGENT, newTag: $FINANCE_IMAGE_TAG }
  - { name: agentcore-demo/payments-mock, newName: $ECR_PAYMENTS_MOCK, newTag: $PAYMENTS_IMAGE_TAG }
patches:
  - target: { kind: ServiceAccount, name: agent-services-worker }
    patch: |-
      - op: add
        path: /metadata/annotations
        value: { eks.amazonaws.com/role-arn: "$AGENT_SERVICES_WORKER_ROLE_ARN" }
  - target: { kind: Deployment, name: agent-services-worker }
    patch: |-
      - op: replace
        path: /spec/template/spec/containers/0/env/9
        value: { name: BEDROCK_MODEL_ID, value: "$model" }
EOF
  # The env index above must be BEDROCK_MODEL_ID (base finance-worker.yaml); check before applying.
  local rendered; rendered="$(k kustomize "$dir")"
  grep -A1 'name: BEDROCK_MODEL_ID' <<<"$rendered" | grep -q "value: $model" \
    || { echo "eks: BEDROCK_MODEL_ID patch did not land on env[9]" >&2; exit 1; }
  log "applying overlays/eks/temporal-workers (Finance model: $model; images $FINANCE_IMAGE_TAG / $PAYMENTS_IMAGE_TAG)"
  k create namespace temporal-workers --dry-run=client -o yaml | k apply -f - >/dev/null   # dry-run=server needs it
  k apply --dry-run=server -f - <<<"$rendered" >/dev/null
  k apply -f - <<<"$rendered" >/dev/null
  k wait --for=condition=Ready certificate/eks-nexus-worker-tls -n temporal-workers --timeout=120s >/dev/null
  k rollout status deploy/payments-mock -n temporal-workers --timeout=300s
  k rollout status deploy/agent-services-worker -n temporal-workers --timeout=300s
}

cmd_scale_finance() {
  kube
  local n="${1:?replicas}"
  k scale deploy/agent-services-worker -n temporal-workers --replicas="$n" >/dev/null
  log "agent-services-worker scaled to $n"
}

case "${1:-}" in
  kubeconfig)
    mkdir -p .temporal
    aws eks update-kubeconfig --name "$CLUSTER" --region "$AWS_REGION" --kubeconfig "$KCFG" --alias "$CONTEXT" \
      | scripts/redact.sh
    chmod 600 "$KCFG"
    ;;
  env)
    echo "export KUBECONFIG=$KCFG"
    ;;
  status)
    kube
    {
      kubectl get nodes -L topology.k8s.aws/zone-id,kubernetes.io/arch,node.kubernetes.io/instance-type
      kubectl -n kube-system get deploy aws-load-balancer-controller coredns
      kubectl -n kube-system get ds aws-node kube-proxy
      kubectl -n cert-manager get deploy
      kubectl -n temporal get pods,svc,certificate 2>/dev/null || true
      kubectl -n temporal-workers get pods,certificate 2>/dev/null || true
    } 2>&1 | scripts/redact.sh
    ;;
  namespace) cmd_namespace ;;
  rds-ca) cmd_rds_ca ;;
  certs) cmd_certs ;;
  values) cmd_values ;;
  temporal) cmd_temporal ;;
  netpol-nlb) cmd_netpol_nlb ;;
  pf) cmd_pf ;;
  pf-stop) cmd_pf_stop ;;
  finance-image) cmd_finance_image ;;
  finance-deploy) cmd_finance_deploy ;;
  scale-finance) shift; cmd_scale_finance "$@" ;;
  *) sed -n '2,25p' "$0"; exit 2 ;;
esac
